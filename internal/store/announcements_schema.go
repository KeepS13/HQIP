package store

import (
	"context"
	"database/sql"
	"errors"
	"regexp"
	"strings"

	"github.com/KeepS13/HQIP/internal/pgstore"
)

// Announcements own their explicit audience and first acknowledgement. No
// browser identifiers, delivery logs, or source artifacts belong in these rows.
const announcementsSchema = `
CREATE TABLE IF NOT EXISTS announcements(id TEXT PRIMARY KEY,title TEXT NOT NULL,body TEXT NOT NULL,mode TEXT NOT NULL CHECK(mode IN ('always','until_acknowledged')),active BIGINT NOT NULL DEFAULT 1,created_at BIGINT NOT NULL);
CREATE INDEX IF NOT EXISTS announcements_time ON announcements(created_at DESC,id DESC);
CREATE TABLE IF NOT EXISTS announcement_recipients(announcement_id TEXT NOT NULL REFERENCES announcements(id),user_id TEXT NOT NULL REFERENCES portal_users(id),acknowledged_at BIGINT NOT NULL DEFAULT 0,PRIMARY KEY(announcement_id,user_id));
CREATE INDEX IF NOT EXISTS announcement_recipients_user ON announcement_recipients(user_id,announcement_id);
`

func postgresAnnouncementsSchema() string {
	// rowid is required by the existing portable snapshot/restore adapter.
	return regexp.MustCompile(`CREATE TABLE IF NOT EXISTS ([a-z_]+)\(`).ReplaceAllString(announcementsSchema, "CREATE TABLE IF NOT EXISTS $1(rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,")
}

func migrateAnnouncements(tx *sql.Tx, postgres bool) error {
	var version string
	err := tx.QueryRow("SELECT value FROM metadata WHERE key='announcements_version'").Scan(&version)
	if err == nil {
		if version != "1" {
			return errors.New("公告 schema 版本不兼容")
		}
		return nil
	}
	if !errors.Is(err, sql.ErrNoRows) {
		return err
	}
	schema := announcementsSchema
	if postgres {
		schema = postgresAnnouncementsSchema()
	}
	for _, statement := range strings.Split(schema, ";") {
		if strings.TrimSpace(statement) != "" {
			if _, err = tx.Exec(statement); err != nil {
				return err
			}
		}
	}
	_, err = tx.Exec("INSERT INTO metadata(key,value) VALUES('announcements_version','1')")
	return err
}

// EnsureAnnouncementsSchema upgrades SQLite atomically and may be repeated.
func EnsureAnnouncementsSchema(db *sql.DB) error {
	tx, err := db.Begin()
	if err != nil {
		return err
	}
	defer tx.Rollback()
	if err = migrateAnnouncements(tx, false); err != nil {
		return err
	}
	return tx.Commit()
}

// MigratePostgresAnnouncements requires the migration role. The shared advisory
// lock serializes schema upgrades; HTTP/runtime roles never perform DDL.
func MigratePostgresAnnouncements(ctx context.Context, dsn string) error {
	db, err := pgstore.Open(dsn)
	if err != nil {
		return err
	}
	defer db.Close()
	tx, err := db.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer tx.Rollback()
	if _, err = tx.ExecContext(ctx, "SELECT pg_advisory_xact_lock(719022634)"); err != nil {
		return err
	}
	if err = migrateAnnouncements(tx, true); err != nil {
		return err
	}
	return tx.Commit()
}
