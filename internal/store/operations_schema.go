package store

import (
	"context"
	"database/sql"
	"errors"
	"regexp"
	"strings"

	"github.com/KeepS13/HQIP/internal/pgstore"
)

// Additive capabilities: neither account sessions nor accounting are reset.
const operationsSchema = `
CREATE TABLE IF NOT EXISTS server_credentials(server_id TEXT PRIMARY KEY REFERENCES servers(id),secret TEXT NOT NULL,binding TEXT NOT NULL,revision BIGINT NOT NULL DEFAULT 1,status TEXT NOT NULL DEFAULT 'unchecked',message TEXT NOT NULL DEFAULT '',updated_at BIGINT NOT NULL,last_checked BIGINT NOT NULL DEFAULT 0,next_check BIGINT NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS server_operations(id TEXT PRIMARY KEY,server_id TEXT NOT NULL REFERENCES servers(id),node_id TEXT NOT NULL DEFAULT '',kind TEXT NOT NULL,state TEXT NOT NULL DEFAULT 'pending',credential_revision BIGINT NOT NULL,binding TEXT NOT NULL,secret TEXT NOT NULL DEFAULT '',target TEXT NOT NULL DEFAULT '',message TEXT NOT NULL DEFAULT '',created_at BIGINT NOT NULL,started_at BIGINT NOT NULL DEFAULT 0,finished_at BIGINT NOT NULL DEFAULT 0);
CREATE INDEX IF NOT EXISTS server_operations_pending ON server_operations(state,created_at);
CREATE UNIQUE INDEX IF NOT EXISTS server_operations_one_running ON server_operations(server_id) WHERE state IN ('running','uncertain');
CREATE TABLE IF NOT EXISTS portal_refresh_receipts(hash TEXT PRIMARY KEY,request_hash TEXT NOT NULL,session_id TEXT NOT NULL REFERENCES portal_sessions(id),response TEXT NOT NULL,current_hash TEXT NOT NULL,expires BIGINT NOT NULL);
`

func postgresOperationsSchema() string {
	return regexp.MustCompile(`CREATE TABLE IF NOT EXISTS ([a-z_]+)\(`).ReplaceAllString(operationsSchema, "CREATE TABLE IF NOT EXISTS $1(rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,")
}

func migrateOperations(tx *sql.Tx, postgres bool) error {
	var version string
	err := tx.QueryRow("SELECT value FROM metadata WHERE key='operations_schema_version'").Scan(&version)
	if err == nil {
		if version != "1" {
			return errors.New("服务器运维 schema 版本不兼容")
		}
		return nil
	}
	if !errors.Is(err, sql.ErrNoRows) {
		return err
	}
	schema := operationsSchema
	if postgres {
		schema = postgresOperationsSchema()
	}
	for _, stmt := range strings.Split(schema, ";") {
		if strings.TrimSpace(stmt) != "" {
			if _, err = tx.Exec(stmt); err != nil {
				return err
			}
		}
	}
	_, err = tx.Exec("INSERT INTO metadata(key,value) VALUES('operations_schema_version','1')")
	return err
}
func EnsureOperationsSchema(db *sql.DB) error {
	tx, err := db.Begin()
	if err != nil {
		return err
	}
	defer tx.Rollback()
	if err = migrateOperations(tx, false); err != nil {
		return err
	}
	return tx.Commit()
}
func MigratePostgresOperations(ctx context.Context, dsn string) error {
	db, err := pgstore.Open(dsn)
	if err != nil {
		return err
	}
	defer db.Close()
	tx, err := db.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer tx.Rollback()
	if _, err = tx.ExecContext(ctx, "SELECT pg_advisory_xact_lock(719022634)"); err != nil {
		return err
	}
	if err = migrateOperations(tx, true); err != nil {
		return err
	}
	return tx.Commit()
}
