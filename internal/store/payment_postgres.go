package store

import (
	"context"
	"database/sql"
	"errors"
	"regexp"
	"strings"
	"time"

	"github.com/KeepS13/HQIP/internal/pgstore"
	"github.com/jackc/pgx/v5/stdlib"
)

// Preserve SQLite row identities for audited offline migration without making
// the PostgreSQL application role an owner of any DDL objects.
func postgresPaymentSchema() string {
	re := regexp.MustCompile(`CREATE TABLE IF NOT EXISTS ([a-z_]+)\(`)
	return re.ReplaceAllString(PaymentSchemaSQL, "CREATE TABLE IF NOT EXISTS $1(rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,")
}

// MigratePostgresPayments must be run explicitly with the DDL/migration role.
// Normal app startup only checks its marker and never attempts CREATE/ALTER.
func MigratePostgresPayments(ctx context.Context, dsn string) error {
	c, err := pgstore.Config(dsn)
	if err != nil {
		return err
	}
	db := stdlib.OpenDB(*c)
	defer db.Close()
	tx, err := db.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer tx.Rollback()
	if _, err = tx.ExecContext(ctx, "SELECT pg_advisory_xact_lock(719022634)"); err != nil {
		return err
	}
	var base, version string
	if err = tx.QueryRowContext(ctx, "SELECT value FROM metadata WHERE key='postgres_schema_version'").Scan(&base); err != nil || base != "1" {
		return errors.New("PostgreSQL 基础版本不兼容")
	}
	err = tx.QueryRowContext(ctx, "SELECT value FROM metadata WHERE key='payments_schema_version'").Scan(&version)
	if err == nil {
		if version != "1" {
			return errors.New("支付 schema 版本不兼容")
		}
		return tx.Commit()
	}
	if !errors.Is(err, sql.ErrNoRows) {
		return err
	}
	for _, statement := range strings.Split(postgresPaymentSchema(), ";") {
		if statement = strings.TrimSpace(statement); statement != "" {
			if _, err = tx.ExecContext(ctx, statement); err != nil {
				return err
			}
		}
	}
	if _, err = tx.ExecContext(ctx, "UPDATE portal_requests SET status='cancelled',note='支付购买流程已启用，原申请流程已停止',decided_at=$1,revision=revision+1 WHERE status='pending'", time.Now().Unix()); err != nil {
		return err
	}
	return tx.Commit()
}
