package store

import (
	"context"
	"database/sql"
	"errors"
	"regexp"
	"strings"

	"github.com/KeepS13/HQIP/internal/pgstore"
)

const offlineSchema = `
CREATE TABLE IF NOT EXISTS portal_offline_grants(lease_id TEXT PRIMARY KEY REFERENCES portal_leases(id),credential_hash TEXT NOT NULL,authorized_at BIGINT NOT NULL,normal_budget BIGINT NOT NULL,normal_unlimited BIGINT NOT NULL,emergency_budget BIGINT NOT NULL,emergency_used BIGINT NOT NULL DEFAULT 0,report_version BIGINT NOT NULL DEFAULT 0,report_body TEXT NOT NULL DEFAULT '',last_active BIGINT NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS portal_emergency_usage(subscription_id TEXT PRIMARY KEY REFERENCES portal_subscriptions(id),used BIGINT NOT NULL DEFAULT 0,reserved BIGINT NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS offline_admission_nodes(node_id TEXT PRIMARY KEY REFERENCES nodes(id),enabled BIGINT NOT NULL DEFAULT 0);
`

func postgresOfflineSchema() string {
	return regexp.MustCompile(`CREATE TABLE IF NOT EXISTS ([a-z_]+)\(`).ReplaceAllString(offlineSchema, "CREATE TABLE IF NOT EXISTS $1(rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,")
}

func migrateOffline(tx *sql.Tx, postgres bool) error {
	var version string
	err := tx.QueryRow("SELECT value FROM metadata WHERE key='offline_admission_version'").Scan(&version)
	if err == nil {
		if version != "1" {
			return errors.New("离线授权 schema 版本不兼容")
		}
		return migrateOnlineIPs(tx)
	}
	if !errors.Is(err, sql.ErrNoRows) {
		return err
	}
	schema := offlineSchema
	if postgres {
		schema = postgresOfflineSchema()
	}
	for _, statement := range strings.Split(schema, ";") {
		if strings.TrimSpace(statement) != "" {
			if _, err = tx.Exec(statement); err != nil {
				return err
			}
		}
	}
	if _, err = tx.Exec("INSERT INTO metadata(key,value) VALUES('offline_admission_version','1')"); err != nil {
		return err
	}
	return migrateOnlineIPs(tx)
}

func EnsureOfflineSchema(db *sql.DB) error {
	tx, err := db.Begin()
	if err != nil {
		return err
	}
	defer tx.Rollback()
	if err = migrateOffline(tx, false); err != nil {
		return err
	}
	return tx.Commit()
}

func MigratePostgresOffline(ctx context.Context, dsn string) error {
	db, err := pgstore.Open(dsn)
	if err != nil {
		return err
	}
	defer db.Close()
	tx, err := db.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer tx.Rollback()
	if _, err = tx.ExecContext(ctx, "SELECT pg_advisory_xact_lock(719022634)"); err != nil {
		return err
	}
	if err = migrateOffline(tx, true); err != nil {
		return err
	}
	return tx.Commit()
}

func (s *Store) OfflineAdmissionEnabled(node string) bool {
	var enabled bool
	return s.DB.QueryRow("SELECT enabled FROM offline_admission_nodes WHERE node_id=?", node).Scan(&enabled) == nil && enabled
}

func (s *Store) SetOfflineAdmissionEnabled(node string, enabled bool) error {
	tx, err := s.DB.Begin()
	if err != nil {
		return err
	}
	defer tx.Rollback()
	if _, err = tx.Exec("INSERT INTO offline_admission_nodes(node_id,enabled) VALUES(?,?) ON CONFLICT(node_id) DO UPDATE SET enabled=excluded.enabled", node, enabled); err != nil {
		return err
	}
	if _, err = tx.Exec("UPDATE nodes SET desired_revision=desired_revision+1 WHERE id=?", node); err != nil {
		return err
	}
	return tx.Commit()
}
