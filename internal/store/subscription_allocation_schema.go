const SubscriptionAllocationSchema = `
CREATE TABLE IF NOT EXISTS subscription_allocations(subscription_id TEXT PRIMARY KEY REFERENCES portal_subscriptions(id),target_count BIGINT NOT NULL CHECK(target_count>=0 AND target_count<=1000),node_ids TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS payment_node_reservations(order_id TEXT PRIMARY KEY REFERENCES payment_orders(id),target_count BIGINT NOT NULL CHECK(target_count>=1 AND target_count<=1000),node_ids TEXT NOT NULL,released BIGINT NOT NULL DEFAULT 0);
` + subscriptionProvisioningSchema // Legacy allocation upgrades also use allocationHolders before renewal migration.

func postgresAllocationSchema() string {
	return regexp.MustCompile(`CREATE TABLE IF NOT EXISTS ([a-z_]+)\(`).ReplaceAllString(SubscriptionAllocationSchema, "CREATE TABLE IF NOT EXISTS $1(rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,")
}

func normalizeSubscriptionTemplate(p *model.SubscriptionTemplate) {
	p.DefaultNodeID = ""
	p.AllocationShortfalls = nil
	if p.NodesPerSubscription == 0 {
		p.NodesPerSubscription = max(1, len(p.NodeIDs))
	}
}

// This upgrade snapshots historical rights; it never resets users, leases,
// usage or credentials. Running it twice must not overwrite live allocations.
func migrateSubscriptionAllocations(tx *sql.Tx, now time.Time, postgres bool) error {
	var version string
	err := tx.QueryRow("SELECT value FROM metadata WHERE key='subscription_allocations_version'").Scan(&version)
	if err == nil {
		if version != "1" {
			return errors.New("订阅节点分配版本不兼容")
		}
		return nil
	}
	if !errors.Is(err, sql.ErrNoRows) {
		return err
	}
	schema := SubscriptionAllocationSchema
	if postgres {
		schema = postgresAllocationSchema()
	}
	for _, stmt := range strings.Split(schema, ";") {
		if strings.TrimSpace(stmt) != "" {
			if _, err = tx.Exec(stmt); err != nil {
				return err
			}
		}
	}
	rows, err := tx.Query("SELECT id,config FROM portal_templates")
	if err != nil {
		return err
	}
	templates := map[string]model.SubscriptionTemplate{}
	for rows.Next() {
		var id, raw string
		var p model.SubscriptionTemplate
		if err = rows.Scan(&id, &raw); err != nil {
			rows.Close()
			return err
		}
		if err = json.Unmarshal([]byte(raw), &p); err != nil {
			rows.Close()
			return err
		}
		normalizeSubscriptionTemplate(&p)
		templates[id] = p
	}
	err = rows.Err()
	rows.Close()
	if err != nil {
		return err
	}
	for id, p := range templates {
		if _, err = tx.Exec("UPDATE portal_templates SET config=? WHERE id=?", jsonString(p), id); err != nil {
			return err
		}
	}
	rows, err = tx.Query("SELECT id,template_id FROM portal_subscriptions")
	if err != nil {
		return err
	}
	type sub struct{ id, template string }
	subs := []sub{}
	for rows.Next() {
		var v sub
		if err = rows.Scan(&v.id, &v.template); err != nil {
			rows.Close()
			return err
		}
		subs = append(subs, v)
	}
	err = rows.Err()
	rows.Close()
	if err != nil {
		return err
	}
	for _, v := range subs {
		ids := templates[v.template].NodeIDs
		if ids == nil {
			ids = []string{}
		}
		if _, err = tx.Exec("INSERT INTO subscription_allocations(subscription_id,target_count,node_ids) VALUES(?,?,?)", v.id, len(ids), jsonString(ids)); err != nil {
			return err
		}
	}
	// This older migration can run before the renewal tables exist.
	legacyOrderSelect := "SELECT " + paymentOrderFields + ", '',0,0 FROM payment_orders o JOIN portal_users u ON u.id=o.user_id "
	rows, err = tx.Query(legacyOrderSelect+"WHERE o.fulfillment_state!='fulfilled' AND (o.payment_state='paid' OR (o.closed_at=0 AND o.creation_state!='failed' AND o.expires_at>?)) ORDER BY o.created_at,o.id", now.Unix())
	if err != nil {
		return err
	}
	orders := []paymentOrderRecord{}
	for rows.Next() {
		r, e := scanPaymentOrder(rows, now)
		if e != nil {
			rows.Close()
			return e
		}
		orders = append(orders, r)
	}
	err = rows.Err()
	rows.Close()
	if err != nil {
		return err
	}
	for _, r := range orders {
		p := templates[r.Order.TemplateID]
		target := r.Order.TemplateSnapshot.NodesPerSubscription
		if target == 0 {
			target = max(1, len(r.Order.TemplateSnapshot.NodeIDs))
		}
		_, err = reserveOrderNodes(tx, r.Order.ID, r.Order.UserID, p, target, now)
		if errors.Is(err, ErrSubscriptionStock) {
			// Preserve the purchased count even when the historical order cannot
			// currently reserve any nodes, including after a late payment.
			if _, err = tx.Exec("INSERT INTO payment_node_reservations(order_id,target_count,node_ids,released) VALUES(?,?,?,1)", r.Order.ID, target, "[]"); err != nil {
				return err
			}
			message := "节点库存不足，已付款订单等待管理员处理"
			if r.Order.PaymentState == "paid" {
				_, err = tx.Exec("UPDATE payment_orders SET fulfillment_state='blocked',last_error=?,revision=revision+1 WHERE id=?", message, r.Order.ID)
			} else {
				message = "节点库存不足，已关闭本地支付入口"
				_, err = tx.Exec("UPDATE payment_orders SET closed_at=?,last_error=?,revision=revision+1 WHERE id=?", now.Unix(), message, r.Order.ID)
			}
			if err != nil {
				return err
			}
			if err = paymentActivity(tx, r.Order.ID, "allocation.unavailable", message, now.Unix()); err != nil {
				return err
			}
		} else if err != nil {
			return err
		}
	}
	_, err = tx.Exec("INSERT INTO metadata(key,value) VALUES('subscription_allocations_version','1')")
	return err
}

func EnsureSubscriptionAllocationSchema(db *sql.DB) error {
	tx, err := db.Begin()
	if err != nil {
		return err
	}
	defer tx.Rollback()
	if err = migrateSubscriptionAllocations(tx, time.Now(), false); err != nil {
		return err
	}
	return tx.Commit()
}

// Use the explicit migration role, with the controller stopped. The normal
// PostgreSQL application role only checks the capability marker at startup.
func MigratePostgresSubscriptionAllocations(ctx context.Context, dsn string) error {
	db, err := pgstore.Open(dsn)
	if err != nil {
		return err
	}
	defer db.Close()
	tx, err := db.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer tx.Rollback()
	if _, err = tx.ExecContext(ctx, "SELECT pg_advisory_xact_lock(719022634)"); err != nil {
		return err
	}
	if err = migrateSubscriptionAllocations(tx, time.Now(), true); err != nil {
		return err
	}
	return tx.Commit()
}
