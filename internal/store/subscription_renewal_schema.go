const subscriptionRenewalSchema = `
CREATE TABLE IF NOT EXISTS subscription_periods(id TEXT PRIMARY KEY,subscription_id TEXT NOT NULL REFERENCES portal_subscriptions(id),starts_at BIGINT NOT NULL,ends_at BIGINT NOT NULL,order_id TEXT NOT NULL DEFAULT '',upload BIGINT NOT NULL DEFAULT 0,download BIGINT NOT NULL DEFAULT 0,reserved BIGINT NOT NULL DEFAULT 0,remainder BIGINT NOT NULL DEFAULT 0,CHECK(ends_at>starts_at));
CREATE INDEX IF NOT EXISTS subscription_period_time ON subscription_periods(subscription_id,starts_at);
CREATE UNIQUE INDEX IF NOT EXISTS subscription_period_order ON subscription_periods(order_id) WHERE order_id!='';
CREATE TABLE IF NOT EXISTS subscription_lease_periods(lease_id TEXT PRIMARY KEY REFERENCES portal_leases(id) ON DELETE CASCADE,period_id TEXT NOT NULL REFERENCES subscription_periods(id));
CREATE INDEX IF NOT EXISTS subscription_period_leases ON subscription_lease_periods(period_id,lease_id);
CREATE TABLE IF NOT EXISTS payment_renewals(order_id TEXT PRIMARY KEY REFERENCES payment_orders(id),subscription_id TEXT NOT NULL REFERENCES portal_subscriptions(id),expected_revision BIGINT NOT NULL,period_id TEXT NOT NULL DEFAULT '');
CREATE INDEX IF NOT EXISTS payment_renewal_subscription ON payment_renewals(subscription_id);
` + subscriptionProvisioningSchema

func postgresSubscriptionRenewalSchema() string {
	return regexp.MustCompile(`CREATE TABLE IF NOT EXISTS ([a-z_]+)\(`).ReplaceAllString(subscriptionRenewalSchema, "CREATE TABLE IF NOT EXISTS $1(rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,")
}

func migrateSubscriptionRenewals(tx *sql.Tx, postgres bool) error {
	var version string
	err := tx.QueryRow("SELECT value FROM metadata WHERE key='subscription_renewals_version'").Scan(&version)
	if err == nil {
		if version == "2" {
			return nil
		}
		if version != "1" {
			return errors.New("订阅续费版本不兼容")
		}
	}
	if err != nil && !errors.Is(err, sql.ErrNoRows) {
		return err
	}
	schema := subscriptionRenewalSchema
	if postgres {
		schema = postgresSubscriptionRenewalSchema()
	}
	for _, statement := range strings.Split(schema, ";") {
		if strings.TrimSpace(statement) != "" {
			if _, err = tx.Exec(statement); err != nil {
				return err
			}
		}
	}
	// Version 2 adds manual activation state; existing periods are untouched.
	// Only a pre-period database needs the original usage-preserving backfill.
	if version == "" {
		// The initial period preserves all historical usage and outstanding holds.
		// No existing lease, credential, order or node allocation is replaced.
		if _, err = tx.Exec(`INSERT INTO subscription_periods(id,subscription_id,starts_at,ends_at,upload,download,reserved,remainder)
SELECT s.id,s.id,s.created_at,s.expires,u.upload,u.download,u.reserved,COALESCE(r.upload+r.download,0)
FROM portal_subscriptions s JOIN portal_usage u ON u.subscription_id=s.id
LEFT JOIN traffic_billing_remainders r ON r.subscription_id=s.id WHERE s.expires>0`); err != nil {
			return err
		}
		if _, err = tx.Exec("INSERT INTO subscription_lease_periods(lease_id,period_id) SELECT id,subscription_id FROM portal_leases"); err != nil {
			return err
		}
	}
	_, err = tx.Exec("INSERT INTO metadata(key,value) VALUES('subscription_renewals_version','2') ON CONFLICT(key) DO UPDATE SET value=excluded.value")
	return err
}

// EnsureSubscriptionRenewalSchema upgrades SQLite atomically before serving
// requests. The caller retains DB ownership. Repeated calls preserve all usage;
// an incompatible version or failed backfill rolls the transaction back.
func EnsureSubscriptionRenewalSchema(db *sql.DB) error {
	tx, err := db.Begin()
	if err != nil {
		return err
	}
	defer tx.Rollback()
	if err = migrateSubscriptionRenewals(tx, false); err != nil {
		return err
	}
	return tx.Commit()
}

// MigratePostgresSubscriptionRenewals uses the migration-role DSN while business
// writers are stopped. It owns its connection, serializes migration attempts
// with the schema advisory lock, and commits the tables and version together.
// Cancellation or failure returns an error without resetting existing ledgers.
func MigratePostgresSubscriptionRenewals(ctx context.Context, dsn string) error {
	db, err := pgstore.Open(dsn)
	if err != nil {
		return err
	}
	defer db.Close()
	tx, err := db.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer tx.Rollback()
	if _, err = tx.ExecContext(ctx, "SELECT pg_advisory_xact_lock(719022634)"); err != nil {
		return err
	}
	if err = migrateSubscriptionRenewals(tx, true); err != nil {
		return err
	}
	return tx.Commit()
}
