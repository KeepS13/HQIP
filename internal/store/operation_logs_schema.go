package store

import (
	"context"
	"database/sql"
	"errors"
	"regexp"
	"strings"

	"github.com/KeepS13/HQIP/internal/pgstore"
)

// This is additive. Existing audit records and their transaction boundaries stay intact.
const operationLogsSchema = `
CREATE TABLE IF NOT EXISTS operation_logs(id TEXT PRIMARY KEY,at_ms BIGINT NOT NULL,last_at_ms BIGINT NOT NULL,category TEXT NOT NULL,action TEXT NOT NULL,actor_type TEXT NOT NULL,actor_id TEXT NOT NULL,actor_name TEXT NOT NULL,auth_type TEXT NOT NULL,resource_type TEXT NOT NULL,resource_id TEXT NOT NULL,method TEXT NOT NULL,route TEXT NOT NULL,ip TEXT NOT NULL,status BIGINT NOT NULL,result TEXT NOT NULL,duration_ms BIGINT NOT NULL,request_id TEXT NOT NULL,job_id TEXT NOT NULL,details TEXT NOT NULL,count BIGINT NOT NULL);
CREATE INDEX IF NOT EXISTS operation_logs_time ON operation_logs(at_ms DESC,id DESC);
CREATE INDEX IF NOT EXISTS operation_logs_action ON operation_logs(action,at_ms DESC);
CREATE INDEX IF NOT EXISTS operation_logs_actor ON operation_logs(actor_id,at_ms DESC);
CREATE INDEX IF NOT EXISTS operation_logs_ip ON operation_logs(ip,at_ms DESC);
CREATE INDEX IF NOT EXISTS operation_logs_request ON operation_logs(request_id);
CREATE INDEX IF NOT EXISTS operation_logs_job ON operation_logs(job_id);
CREATE TABLE IF NOT EXISTS operation_job_context(job_id TEXT PRIMARY KEY,request_id TEXT NOT NULL,actor_type TEXT NOT NULL,actor_id TEXT NOT NULL,actor_name TEXT NOT NULL,ip TEXT NOT NULL,created_at BIGINT NOT NULL);
CREATE INDEX IF NOT EXISTS operation_job_context_created ON operation_job_context(created_at);
`

func postgresOperationLogsSchema() string {
	return regexp.MustCompile(`CREATE TABLE IF NOT EXISTS ([a-z_]+)\(`).ReplaceAllString(operationLogsSchema, "CREATE TABLE IF NOT EXISTS $1(rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,")
}

func migrateOperationLogs(tx *sql.Tx, postgres bool) error {
	var version string
	err := tx.QueryRow("SELECT value FROM metadata WHERE key='operation_logs_version'").Scan(&version)
	if err == nil {
		if version != "1" {
			return errors.New("操作日志 schema 版本不兼容")
		}
		return nil
	}
	if !errors.Is(err, sql.ErrNoRows) {
		return err
	}
	schema := operationLogsSchema
	if postgres {
		schema = postgresOperationLogsSchema()
	}
	for _, statement := range strings.Split(schema, ";") {
		if strings.TrimSpace(statement) != "" {
			if _, err = tx.Exec(statement); err != nil {
				return err
			}
		}
	}
	_, err = tx.Exec("INSERT INTO metadata(key,value) VALUES('operation_logs_version','1')")
	return err
}

func EnsureOperationLogsSchema(db *sql.DB) error {
	tx, err := db.Begin()
	if err != nil {
		return err
	}
	defer tx.Rollback()
	if err = migrateOperationLogs(tx, false); err != nil {
		return err
	}
	return tx.Commit()
}

func MigratePostgresOperationLogs(ctx context.Context, dsn string) error {
	db, err := pgstore.Open(dsn)
	if err != nil {
		return err
	}
	defer db.Close()
	tx, err := db.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer tx.Rollback()
	if _, err = tx.ExecContext(ctx, "SELECT pg_advisory_xact_lock(719022634)"); err != nil {
		return err
	}
	if err = migrateOperationLogs(tx, true); err != nil {
		return err
	}
	return tx.Commit()
}
