package store

import (
	"context"
	"database/sql"
	"errors"
	"github.com/KeepS13/HQIP/internal/pgstore"
	"regexp"
	"strings"
)

const trafficBillingSchema = `
CREATE TABLE IF NOT EXISTS traffic_billing_settings(id BIGINT PRIMARY KEY,enabled BIGINT NOT NULL,revision BIGINT NOT NULL,hy2 BIGINT NOT NULL,vless BIGINT NOT NULL);
INSERT INTO traffic_billing_settings(id,enabled,revision,hy2,vless) VALUES(1,0,1,150,150) ON CONFLICT(id) DO NOTHING;
CREATE TABLE IF NOT EXISTS traffic_billing_changes(revision BIGINT PRIMARY KEY,actor TEXT NOT NULL,at BIGINT NOT NULL,before_config TEXT NOT NULL,after_config TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS traffic_lease_billing(lease_id TEXT PRIMARY KEY,state TEXT NOT NULL,remaining_units BIGINT NOT NULL DEFAULT 0,remaining_emergency BIGINT NOT NULL DEFAULT 0);
CREATE TABLE IF NOT EXISTS traffic_billing_remainders(subscription_id TEXT PRIMARY KEY,upload BIGINT NOT NULL DEFAULT 0,download BIGINT NOT NULL DEFAULT 0);
INSERT INTO metadata(key,value) VALUES('traffic_billing_version','1') ON CONFLICT(key) DO NOTHING;
`

func postgresTrafficBillingSchema() string {
	return regexp.MustCompile(`CREATE TABLE IF NOT EXISTS ([a-z_]+)\(`).ReplaceAllString(trafficBillingSchema, "CREATE TABLE IF NOT EXISTS $1(rowid BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,")
}

func migrateTrafficBilling(tx *sql.Tx, postgres bool) error {
	var version string
	err := tx.QueryRow("SELECT value FROM metadata WHERE key='traffic_billing_version'").Scan(&version)
	if err == nil && version != "1" {
		return errors.New("traffic billing schema is incompatible")
	}
	if err != nil && !errors.Is(err, sql.ErrNoRows) {
		return err
	}
	schema := trafficBillingSchema
	if postgres {
		schema = postgresTrafficBillingSchema()
	}
	for _, statement := range strings.Split(schema, ";") {
		if strings.TrimSpace(statement) != "" {
			if _, err = tx.Exec(statement); err != nil {
				return err
			}
		}
	}
	return nil
}

func EnsureTrafficBillingSchema(db *sql.DB) error {
	tx, err := db.Begin()
	if err != nil {
		return err
	}
	defer tx.Rollback()
	if err = migrateTrafficBilling(tx, false); err != nil {
		return err
	}
	return tx.Commit()
}

func MigratePostgresTrafficBilling(ctx context.Context, dsn string) error {
	db, err := pgstore.Open(dsn)
	if err != nil {
		return err
	}
	defer db.Close()
	tx, err := db.BeginTx(ctx, nil)
	if err != nil {
		return err
	}
	defer tx.Rollback()
	if _, err = tx.ExecContext(ctx, "SELECT pg_advisory_xact_lock(719022634)"); err != nil {
		return err
	}
	if err = migrateTrafficBilling(tx, true); err != nil {
		return err
	}
	return tx.Commit()
}
